/* 显示一个 8x16 ASCII 字符，小写字母会自动转换为大写。 */
void OLED_ShowChar(uint8_t x, uint8_t y, char ch, uint8_t color)
{
    uint8_t row;
    uint8_t column;
    uint8_t bits;
    uint8_t index;
    char upper = ch;

    if ((upper >= 'a') && (upper <= 'z'))
    {
        upper = (char)(upper - ('a' - 'A'));
    }
    if ((upper < ' ') || (upper > '_'))
    {
        upper = '?';
    }

    index = (uint8_t)(upper - ' ');
    for (row = 0u; row < 16u; row++)
    {
        bits = oled_font8x16_ascii[index][row];
        for (column = 0u; column < 8u; column++)
        {
            if ((bits & 0x80u) != 0u)
            {
                OLED_DrawPoint((uint8_t)(x + column), (uint8_t)(y + row), color);
            }
            else
            {
                OLED_DrawPoint((uint8_t)(x + column), (uint8_t)(y + row),
                               (uint8_t)(color == 0u ? 1u : 0u));
            }
            bits <<= 1;
        }
    }
}

/* 显示 ASCII 字符串，超出右边界时自动换行。 */
void OLED_ShowString(uint8_t x, uint8_t y, const char *text, uint8_t color)
{
    while ((text != 0) && (*text != '\0'))
    {
        if ((uint16_t)x + 8u > 128u)
        {
            x = 0u;
            y = (uint8_t)(y + 16u);
        }
        if ((uint16_t)y + 16u > 64u)
        {
            break;
        }
        OLED_ShowChar(x, y, *text, color);
        x = (uint8_t)(x + 8u);
        text++;
    }
}

/*
 * 显示页式单色位图。
 * 数据格式：按页、按列、每字节 bit0 位于该页顶部。
 * mode=1 时位 1 点亮，mode=0 时位 1 熄灭。
 */
void OLED_ShowPicture(uint8_t x, uint8_t y, uint8_t sizex, uint8_t sizey,
                      const uint8_t BMP[], uint8_t mode)
{
    uint16_t index = 0u;
    uint8_t page;
    uint8_t column;
    uint8_t bit;
    uint8_t value;
    uint8_t pages = (uint8_t)((sizey + 7u) / 8u);

    for (page = 0u; page < pages; page++)
    {
        for (column = 0u; column < sizex; column++)
        {
            value = BMP[index];
            index++;

            for (bit = 0u; bit < 8u; bit++)
            {
                if ((value & 0x01u) != 0u)
                {
                    OLED_DrawPoint((uint8_t)(x + column),
                                   (uint8_t)(y + page * 8u + bit), mode);
                }
                else
                {
                    OLED_DrawPoint((uint8_t)(x + column),
                                   (uint8_t)(y + page * 8u + bit),
                                   (uint8_t)(mode == 0u ? 1u : 0u));
                }
                value >>= 1;
            }
        }
    }
}
