#include "oled.h"
#include "delay.h"

/*
 * GM009605 1.9 英寸 128x64 OLED 驱动。
 * 该模块使用 SSD1306/SSD1315 兼容控制器，7 位 I2C 地址通常为 0x3C 或 0x3D。
 * 原驱动发送了 SH1106 的 0xFD 命令，却漏掉 SSD1306 必需的电荷泵 0x8D/0x14，
 * 会导致屏幕有供电但完全不亮，因此这里改为完整的 SSD1306 初始化序列。
 */

#define OLED_I2C_DELAY_US       2u      /* 约 250 kHz，兼顾稳定性和动画刷新速度 */
#define OLED_I2C_ADDR_3C        0x78u   /* 7 位地址 0x3C 左移一位 */
#define OLED_I2C_ADDR_3D        0x7Au   /* 7 位地址 0x3D 左移一位 */
#define OLED_I2C_TIMEOUT_RETRY  200u    /* 无应答时的二次探测等待时间 */

uint8_t OLED_GRAM[144][8];

static uint8_t oled_i2c_address = OLED_I2C_ADDR_3C;
static uint8_t oled_is_ready = 0u;

/* 读取 SDA 的实际电平，用于判断从机 ACK。 */
static uint8_t OLED_ReadSDA(void)
{
    return (GPIO_ReadInputDataBit(OLED_SDA_PORT, OLED_SDA_PIN) == Bit_SET) ? 1u : 0u;
}

/* I2C 开始信号。 */
void OLED_I2C_Start(void)
{
    OLED_SDA_Set();
    OLED_SCL_Set();
    delay_us(OLED_I2C_DELAY_US);
    OLED_SDA_Clr();
    delay_us(OLED_I2C_DELAY_US);
    OLED_SCL_Clr();
    delay_us(OLED_I2C_DELAY_US);
}

/* I2C 停止信号。 */
void OLED_I2C_Stop(void)
{
    OLED_SDA_Clr();
    delay_us(OLED_I2C_DELAY_US);
    OLED_SCL_Set();
    delay_us(OLED_I2C_DELAY_US);
    OLED_SDA_Set();
    delay_us(OLED_I2C_DELAY_US);
}

/*
 * 发送一个字节并读取第 9 个时钟的 ACK。
 * 返回值 1 表示从机应答，0 表示无应答。
 */
uint8_t OLED_I2C_WriteByte(uint8_t data)
{
    uint8_t bit;
    uint8_t ack;

    for (bit = 0u; bit < 8u; bit++)
    {
        if ((data & 0x80u) != 0u)
        {
            OLED_SDA_Set();
        }
        else
        {
            OLED_SDA_Clr();
        }

        delay_us(OLED_I2C_DELAY_US);
        OLED_SCL_Set();
        delay_us(OLED_I2C_DELAY_US);
        OLED_SCL_Clr();
        delay_us(OLED_I2C_DELAY_US);
        data <<= 1;
    }

    /* 释放 SDA，等待 OLED 拉低 SDA 产生 ACK。 */
    OLED_SDA_Set();
    delay_us(OLED_I2C_DELAY_US);
    OLED_SCL_Set();
    delay_us(OLED_I2C_DELAY_US);
    ack = (OLED_ReadSDA() == 0u) ? 1u : 0u;
    OLED_SCL_Clr();
    delay_us(OLED_I2C_DELAY_US);

    return ack;
}

/* 探测指定 I2C 地址是否存在应答。 */
static uint8_t OLED_I2C_Probe(uint8_t address)
{
    uint8_t ack;

    OLED_I2C_Start();
    ack = OLED_I2C_WriteByte(address);
    OLED_I2C_Stop();

    return ack;
}

/* 向 OLED 发送一个命令或数据字节。 */
uint8_t OLED_WR_Byte(uint8_t data, uint8_t mode)
{
    uint8_t ok;

    OLED_I2C_Start();
    ok = OLED_I2C_WriteByte(oled_i2c_address);
    if (ok != 0u)
    {
        ok = OLED_I2C_WriteByte((mode != 0u) ? 0x40u : 0x00u);
    }
    if (ok != 0u)
    {
        ok = OLED_I2C_WriteByte(data);
    }
    OLED_I2C_Stop();

    return ok;
}

/* 命令和数据的简洁封装。 */
static uint8_t OLED_WriteCommand(uint8_t command)
{
    return OLED_WR_Byte(command, OLED_CMD);
}

/* 总线恢复：若上一次复位时从机把 SDA 拉低，用 9 个时钟释放总线。 */
static void OLED_I2C_BusRecovery(void)
{
    uint8_t i;

    OLED_SDA_Set();
    for (i = 0u; i < 9u; i++)
    {
        OLED_SCL_Clr();
        delay_us(OLED_I2C_DELAY_US);
        OLED_SCL_Set();
        delay_us(OLED_I2C_DELAY_US);
    }
    OLED_I2C_Stop();
}

/* 完整的 SSD1306 128x64 初始化序列。 */
void OLED_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStructure;

    oled_is_ready = 0u;
    oled_i2c_address = OLED_I2C_ADDR_3C;

    /* 让 1.9 英寸 OLED 的电源和内部复位稳定后再访问总线。 */
    delay_ms(150);

    RCC_AHB1PeriphClockCmd(RCC_AHB1Periph_GPIOG, ENABLE);

    GPIO_InitStructure.GPIO_Pin = OLED_SDA_PIN | OLED_SCL_PIN;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_OUT;
    GPIO_InitStructure.GPIO_OType = GPIO_OType_OD;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_100MHz;
    GPIO_InitStructure.GPIO_PuPd = GPIO_PuPd_UP;
    GPIO_Init(OLED_SDA_PORT, &GPIO_InitStructure);

    OLED_SDA_Set();
    OLED_SCL_Set();
    delay_ms(10);
    OLED_I2C_BusRecovery();

    /* 兼容常见的 0x3C 和 0x3D 两种地址。 */
    if (OLED_I2C_Probe(OLED_I2C_ADDR_3C) != 0u)
    {
        oled_i2c_address = OLED_I2C_ADDR_3C;
        oled_is_ready = 1u;
    }
    else if (OLED_I2C_Probe(OLED_I2C_ADDR_3D) != 0u)
    {
        oled_i2c_address = OLED_I2C_ADDR_3D;
        oled_is_ready = 1u;
    }
    else
    {
        /* 部分模块上电较慢，稍后再次确认。 */
        delay_ms(OLED_I2C_TIMEOUT_RETRY);
        if (OLED_I2C_Probe(OLED_I2C_ADDR_3C) != 0u)
        {
            oled_i2c_address = OLED_I2C_ADDR_3C;
            oled_is_ready = 1u;
        }
        else if (OLED_I2C_Probe(OLED_I2C_ADDR_3D) != 0u)
        {
            oled_i2c_address = OLED_I2C_ADDR_3D;
            oled_is_ready = 1u;
        }
    }

    /* SSD1306 标准初始化：包含电荷泵、页寻址、128x64 复用等关键配置。 */
    OLED_WriteCommand(0xAEu);          /* 关闭显示 */
    OLED_WriteCommand(0x20u);          /* 设置内存寻址模式 */
    OLED_WriteCommand(0x02u);          /* 页寻址模式 */
    OLED_WriteCommand(0xD5u);          /* 显示时钟分频 */
    OLED_WriteCommand(0x80u);
    OLED_WriteCommand(0xA8u);          /* 复用率 1/64 */
    OLED_WriteCommand(0x3Fu);
    OLED_WriteCommand(0xD3u);          /* 显示偏移 */
    OLED_WriteCommand(0x00u);
    OLED_WriteCommand(0x40u);          /* 起始行 0 */
    OLED_WriteCommand(0x8Du);          /* SSD1306 电荷泵设置 */
    OLED_WriteCommand(0x14u);          /* 必须开启内部电荷泵 */
    OLED_WriteCommand(0xA1u);          /* 段重映射 */
    OLED_WriteCommand(0xC8u);          /* COM 反向扫描 */
    OLED_WriteCommand(0xDAu);          /* COM 引脚配置 */
    OLED_WriteCommand(0x12u);
    OLED_WriteCommand(0x81u);          /* 对比度 */
    OLED_WriteCommand(0xCFu);
    OLED_WriteCommand(0xD9u);          /* 预充电周期 */
    OLED_WriteCommand(0xF1u);
    OLED_WriteCommand(0xDBu);          /* VCOMH */
    OLED_WriteCommand(0x40u);
    OLED_WriteCommand(0xA4u);          /* 显示跟随 RAM */
    OLED_WriteCommand(0xA6u);          /* 正常显示，非反色 */
    OLED_WriteCommand(0x2Eu);          /* 关闭滚动 */
    OLED_WriteCommand(0xAFu);          /* 开启显示 */
    delay_ms(100);

    OLED_Clear();
}

/* 返回检测到的 I2C 从机地址。 */
uint8_t OLED_GetI2CAddress(void)
{
    return oled_i2c_address;
}

/* 返回 1 表示初始化阶段检测到 OLED ACK。 */
uint8_t OLED_IsReady(void)
{
    return oled_is_ready;
}

/* 正常/反色显示。 */
void OLED_ColorTurn(uint8_t i)
{
    OLED_WriteCommand((i != 0u) ? 0xA7u : 0xA6u);
}

/* 屏幕旋转 180 度。 */
void OLED_DisplayTurn(uint8_t i)
{
    if (i == 0u)
    {
        OLED_WriteCommand(0xC8u);
        OLED_WriteCommand(0xA1u);
    }
    else
    {
        OLED_WriteCommand(0xC0u);
        OLED_WriteCommand(0xA0u);
    }
}

void OLED_DisPlay_On(void)
{
    OLED_WriteCommand(0xAFu);
}

void OLED_DisPlay_Off(void)
{
    OLED_WriteCommand(0xAEu);
}

/* 把 128x64 显存写入 SSD1306。 */
void OLED_Refresh(void)
{
    uint8_t page;
    uint8_t column;
    uint8_t ok;

    for (page = 0u; page < 8u; page++)
    {
        OLED_WriteCommand((uint8_t)(0xB0u + page));
        OLED_WriteCommand(0x00u);      /* 低列地址 */
        OLED_WriteCommand(0x10u);      /* 高列地址 */

        OLED_I2C_Start();
        ok = OLED_I2C_WriteByte(oled_i2c_address);
        if (ok != 0u)
        {
            ok = OLED_I2C_WriteByte(0x40u);
        }

        if (ok != 0u)
        {
            for (column = 0u; column < 128u; column++)
            {
                if (OLED_I2C_WriteByte(OLED_GRAM[column][page]) == 0u)
                {
                    break;
                }
            }
        }
        OLED_I2C_Stop();
    }
}

/* 清空显存并刷新屏幕。 */
void OLED_Clear(void)
{
    uint8_t page;
    uint8_t column;

    for (page = 0u; page < 8u; page++)
    {
        for (column = 0u; column < 128u; column++)
        {
            OLED_GRAM[column][page] = 0x00u;
        }
    }
    OLED_Refresh();
}

/* 清除一个像素。 */
void OLED_ClearPoint(uint8_t x, uint8_t y)
{
    OLED_DrawPoint(x, y, 0u);
}

/* 设置或清除一个像素。 */
void OLED_DrawPoint(uint8_t x, uint8_t y, uint8_t t)
{
    uint8_t page;
    uint8_t bit;
    uint8_t mask;

    if ((x >= 128u) || (y >= 64u))
    {
        return;
    }

    page = (uint8_t)(y / 8u);
    bit = (uint8_t)(y % 8u);
    mask = (uint8_t)(1u << bit);

    if (t != 0u)
    {
        OLED_GRAM[x][page] |= mask;
    }
    else
    {
        OLED_GRAM[x][page] &= (uint8_t)(~mask);
    }
}

